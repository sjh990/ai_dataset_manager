@dataclass
class PipelineConfig:
    dataset_dir: str = ""
    output_dir: str = ""
    task: str = "detect"
    yolo_version: str = "YOLO11"
    class_names: list = field(default_factory=list)
    kpt_shape: list | None = None
    flip_idx: list | None = None
    split: dict = field(default_factory=lambda: dict(train=70, val=20, test=10, seed=42,
                                                     stratify=True, keep_existing=False))
    preprocess: dict = field(default_factory=dict)  # {op_key: params}
    augment: dict = field(default_factory=dict)     # {op_key: params}
    aug_common: dict = field(default_factory=common_defaults)
    multiplier: int = 3
    include_original: bool = True
    augment_splits: list = field(default_factory=lambda: ["train"])
    image_format: str = "keep"  # keep | jpg | png
    jpeg_quality: int = 95
    workers: int = 4
    seed: int = 42

    def to_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False, indent=2)

    @classmethod
    def from_dict(cls, d: dict) -> "PipelineConfig":
        known = {k: v for k, v in d.items() if k in cls.__dataclass_fields__}
        return cls(**known)


ProgressCB = Callable[[int, int, str], None]
LogCB = Callable[[str], None]


CLASSIFY_SKIP_PRE = ("tile", "filter_small", "drop_empty")  # 분류는 객체 라벨이 없으므로 무의미
CLASSIFY_SKIP_AUG = ("mosaic",)                            # 4장 합성은 이미지 클래스가 섞임


def effective_ops(cfg: "PipelineConfig") -> tuple[dict, dict]:
    if cfg.task != "classify":
        return cfg.preprocess, cfg.augment
    return ({k: v for k, v in cfg.preprocess.items() if k not in CLASSIFY_SKIP_PRE},
            {k: v for k, v in cfg.augment.items() if k not in CLASSIFY_SKIP_AUG})


def _kpt(cfg):
    return tuple(cfg.kpt_shape) if cfg.kpt_shape else None


def load_sample(sample: Sample, cfg: PipelineConfig, stats=None):
    img = imread(sample.image)
    if img is None:
        return None, []
    if cfg.task == "classify":
        return img, []
    h, w = img.shape[:2]
    anns = parse_labels(sample.label, cfg.task, w, h, _kpt(cfg), stats)
    return img, anns


def write_classify_info(cfg: "PipelineConfig", out: Path, split_sizes: dict):
    """Ultralytics classify는 data.yaml 없이 폴더 경로(out)를 data로 지정한다."""
    (out / "classes.txt").write_text("\n".join(cfg.class_names) + "\n", encoding="utf-8")
    (out / "README_classify.txt").write_text(
        f"# Generated by YOLO Dataset Augmentor v{__version__} — task: classify / {cfg.yolo_version}\n"
        "구조: <split>/<클래스>/<이미지>\n"
        f"학습 예: yolo classify train data=\"{str(out.resolve())}\" model=yolo11n-cls.pt\n"
        "(val 폴더가 없으면 Ultralytics가 test 폴더를 검증에 사용합니다.)\n", encoding="utf-8")


def write_data_yaml(cfg: PipelineConfig, out: Path, split_sizes: dict):
    style = VERSIONS.get(cfg.yolo_version, {}).get("names_style", "dict")
    names = list(cfg.class_names)
    d: dict = {"path": str(out.resolve()).replace("\\", "/"),
               "train": "images/train",
               "val": "images/val" if split_sizes.get("val") else "images/train"}
    if split_sizes.get("test"):
        d["test"] = "images/test"
    d["nc"] = len(names)
    d["names"] = names if style == "list" else {i: n for i, n in enumerate(names)}
    if cfg.task == "pose" and cfg.kpt_shape:
        d["kpt_shape"] = list(cfg.kpt_shape)
        if cfg.flip_idx:
            d["flip_idx"] = list(cfg.flip_idx)
    header = (f"# Generated by YOLO Dataset Augmentor v{__version__}\n"
              f"# target model: {cfg.yolo_version} / task: {cfg.task}\n")
    (out / "data.yaml").write_text(header + yaml.safe_dump(d, allow_unicode=True, sort_keys=False),
                                   encoding="utf-8")


def run_pipeline(cfg: PipelineConfig, progress: ProgressCB | None = None, log: LogCB | None = None,
                 cancel: threading.Event | None = None) -> dict:
    progress = progress or (lambda *a: None)
    log = log or print
    cancel = cancel or threading.Event()
    t0 = time.time()
    out = Path(cfg.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    log("데이터셋 스캔 중…")
    info = scan_dataset(cfg.dataset_dir, exclude=out)
    if not info.samples:
        raise RuntimeError("이미지를 찾지 못했습니다.")
    if not cfg.class_names or cfg.task == "classify":
        analyze_dataset(info)
        if not cfg.class_names or cfg.task == "classify":
            cfg.class_names = info.class_names
    is_cls = cfg.task == "classify"
    if is_cls and not all(s.cls_name for s in info.samples):
        raise RuntimeError("Classification 데이터셋은 [<split>/]<클래스>/이미지 폴더 구조여야 합니다.")
    pre_ops, aug_ops = effective_ops(cfg)
    if is_cls:
        skipped = [k for k in list(cfg.preprocess) + list(cfg.augment) if k not in pre_ops and k not in aug_ops]
        if skipped:
            log("Classification에서는 적용하지 않는 항목: " + ", ".join(skipped))

    sp = cfg.split
    splits = split_samples(info.samples, sp["train"], sp["val"], sp["test"], int(sp.get("seed", 42)),
                           bool(sp.get("stratify", True)), bool(sp.get("keep_existing", False)))
    log("분할: " + ", ".join(f"{k} {len(v)}장" for k, v in splits.items()))
    for s in SPLITS:
        if splits[s] and not is_cls:
            (out / "images" / s).mkdir(parents=True, exist_ok=True)
            (out / "labels" / s).mkdir(parents=True, exist_ok=True)

    # 출력 파일명 중복 방지
    names: dict[int, str] = {}
    for s, lst in splits.items():
        used: Counter = Counter()
        for smp in lst:
            stem = smp.image.stem
            key = (smp.cls_name, stem)
            if used[key]:
                stem = f"{stem}_{used[key]}"
            used[key] += 1
            names[id(smp)] = stem
    cls_idx = {n: i for i, n in enumerate(cfg.class_names)}

    kpt_dim = cfg.kpt_shape[1] if cfg.kpt_shape else 3
    flip_idx = cfg.flip_idx
    lock = threading.Lock()
    stats = defaultdict(int)
    written = Counter()
    inst = {s: Counter() for s in SPLITS}
    errors: list[str] = []

    def save(split, stem, img, anns, src_ext, cls_name=None):
        ext = src_ext if cfg.image_format == "keep" else "." + cfg.image_format
        if is_cls:
            d = out / split / cls_name
            d.mkdir(parents=True, exist_ok=True)
            imwrite(d / f"{stem}{ext}", img, cfg.jpeg_quality)
            with lock:
                written[split] += 1
                inst[split][cls_idx.get(cls_name, 0)] += 1
            return
        imwrite(out / "images" / split / f"{stem}{ext}", img, cfg.jpeg_quality)
        h, w = img.shape[:2]
        (out / "labels" / split / f"{stem}.txt").write_text(
            format_labels(anns, cfg.task, w, h, kpt_dim), encoding="utf-8")
        with lock:
            written[split] += 1
            for a in anns:
                inst[split][a.cls] += 1

    def make_mosaic_provider(split, rng):
        pool = splits[split]

        def provider(n):
            res = []
            for _ in range(n * 3):
                if len(res) >= n:
                    break
                smp = pool[int(rng.integers(len(pool)))]
                img, anns = load_sample(smp, cfg)
                if img is None:
                    continue
                pieces = preprocess(img, anns, pre_ops, cfg.task, rng, flip_idx)
                if pieces:
                    _, pi, pa = pieces[int(rng.integers(len(pieces)))]
                    res.append((pi, pa))
            return res
        return provider

    def work(idx, split, smp):
        if cancel.is_set():
            return
        rng = np.random.default_rng([int(cfg.seed), idx])
        local: dict = {}
        img, anns = load_sample(smp, cfg)
        if img is None:
            with lock:
                errors.append(f"읽기 실패: {smp.image}")
            return
        pieces = preprocess(img, anns, pre_ops, cfg.task, rng, flip_idx, local)
        do_aug = split in cfg.augment_splits and aug_ops and cfg.multiplier > 0
        provider = make_mosaic_provider(split, rng) if (do_aug and "mosaic" in aug_ops) else None
        stem = names[id(smp)]
        ext = smp.image.suffix.lower()
        for suffix, pimg, panns in pieces:
            if cancel.is_set():
                return
            if cfg.include_original or not do_aug:
                save(split, stem + suffix, pimg, panns, ext, smp.cls_name)
            if do_aug:
                for k in range(int(cfg.multiplier)):
                    aimg, aanns, d = augment(pimg, panns, aug_ops, cfg.aug_common, rng, cfg.task,
                                             flip_idx, provider)
                    local["aug_dropped"] = local.get("aug_dropped", 0) + d
                    save(split, f"{stem}{suffix}_aug{k + 1}", aimg, aanns, ext, smp.cls_name)
        with lock:
            for k, v in local.items():
                stats[k] += v

    jobs = [(s, smp) for s in SPLITS for smp in splits[s]]
    total = len(jobs)
    done = 0
    prev_threads = cv2.getNumThreads()
    workers = max(1, int(cfg.workers))
    if workers > 1:
        cv2.setNumThreads(1)
    try:
        with ThreadPoolExecutor(max_workers=workers) as ex:
            futs = {ex.submit(work, i, s, smp): (s, smp) for i, (s, smp) in enumerate(jobs)}
            for f in as_completed(futs):
                try:
                    f.result()
                except Exception as e:  # 개별 이미지 오류는 기록하고 계속
                    s, smp = futs[f]
                    errors.append(f"{smp.image.name}: {type(e).__name__}: {e}")
                done += 1
                progress(done, total, f"{futs[f][1].image.name}")
                if cancel.is_set():
                    for ff in futs:
                        ff.cancel()
                    break
    finally:
        cv2.setNumThreads(prev_threads)

    if is_cls:
        write_classify_info(cfg, out, dict(written))
    else:
        write_data_yaml(cfg, out, dict(written))
    (out / "augment_config.json").write_text(cfg.to_json(), encoding="utf-8")
    summary = dict(
        cancelled=cancel.is_set(),
        seconds=round(time.time() - t0, 1),
        source_images=len(info.samples),
        split_source={k: len(v) for k, v in splits.items()},
        written=dict(written),
        instances={s: {cfg.class_names[c] if c < len(cfg.class_names) else str(c): n
                       for c, n in sorted(inst[s].items())} for s in SPLITS if written[s]},
        removed=dict(stats),
        errors=errors[:50],
        n_errors=len(errors),
        output_dir=str(out.resolve()),
    )
    (out / "report.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    for e in errors[:10]:
        log("⚠ " + e)
    log(f"완료: {dict(written)} ({summary['seconds']}s)")
    return summary


def preview_samples(cfg: PipelineConfig, sample: Sample, n_aug: int = 4, seed: int | None = None,
                    pool: list[Sample] | None = None):
    """GUI 미리보기: (원본, 원본라벨), [(전처리 결과)], [(증강 결과)…]"""
    rng = np.random.default_rng(seed)
    img, anns = load_sample(sample, cfg)
    if img is None:
        return None
    pre_ops, aug_ops = effective_ops(cfg)
    pieces = preprocess(img, anns, pre_ops, cfg.task, np.random.default_rng(0), cfg.flip_idx)
    if not pieces:  # 빈 이미지 제거 등으로 사라진 경우 원본 사용
        pieces = [("", img, anns)]
    # 라벨이 가장 많은 조각을 미리보기 대상으로
    base = max(pieces, key=lambda p: len(p[2]))
    provider = None
    if "mosaic" in aug_ops and pool:
        def provider(k):
            res = []
            for _ in range(k * 3):
                if len(res) >= k:
                    break
                s = pool[int(rng.integers(len(pool)))]
                im2, an2 = load_sample(s, cfg)
                if im2 is None:
                    continue
                pc = preprocess(im2, an2, pre_ops, cfg.task, rng, cfg.flip_idx)
                if pc:
                    res.append((pc[0][1], pc[0][2]))
            return res
    augs = []
    for _ in range(n_aug):
        a_img, a_anns, _ = augment(base[1], base[2], aug_ops, cfg.aug_common, rng, cfg.task,
                                   cfg.flip_idx, provider)
        augs.append((a_img, a_anns))
    return (img, anns), pieces, base, augs
